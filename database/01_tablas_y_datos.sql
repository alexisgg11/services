-- Cuatro tablas del catálogo de abastecimiento. No modifica el esquema public.
CREATE SCHEMA IF NOT EXISTS panaderia;
CREATE TABLE IF NOT EXISTS panaderia.tipo_producto (
 id_tipo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 descripcion VARCHAR(80) NOT NULL UNIQUE CHECK (length(trim(descripcion)) > 0)
);
CREATE TABLE IF NOT EXISTS panaderia.proveedor (
 id_proveedor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ruc VARCHAR(11) NOT NULL UNIQUE CHECK (ruc ~ '^[0-9]{11}$'),
 nombre VARCHAR(120) NOT NULL CHECK (length(trim(nombre)) > 0)
);
CREATE TABLE IF NOT EXISTS panaderia.unidad_medida (
 id_unidad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 descripcion VARCHAR(50) NOT NULL UNIQUE CHECK (length(trim(descripcion)) > 0),
 simbolo VARCHAR(10) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS panaderia.producto (
 id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 descripcion VARCHAR(150) NOT NULL CHECK (length(trim(descripcion)) > 0),
 precio NUMERIC(10,2) NOT NULL CHECK (precio >= 0),
 id_tipo INTEGER NOT NULL REFERENCES panaderia.tipo_producto(id_tipo) ON DELETE RESTRICT,
 id_proveedor INTEGER NOT NULL REFERENCES panaderia.proveedor(id_proveedor) ON DELETE RESTRICT,
 id_unidad INTEGER NOT NULL REFERENCES panaderia.unidad_medida(id_unidad) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS idx_producto_tipo ON panaderia.producto(id_tipo);
CREATE INDEX IF NOT EXISTS idx_producto_proveedor ON panaderia.producto(id_proveedor);
CREATE INDEX IF NOT EXISTS idx_producto_unidad ON panaderia.producto(id_unidad);
CREATE INDEX IF NOT EXISTS idx_producto_precio ON panaderia.producto(precio DESC);
